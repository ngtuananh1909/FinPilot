#!/usr/bin/env node
// Generates src/lib/demo/fixtures.generated.ts from the synthetic seed SOURCE files in
// mock-data/. The app bundles the generated module instead of reading mock-data/ at runtime
// (no filesystem dependency on Amplify, and CSV/JSON never act as a runtime database).
//
//   node tools/generate-demo-fixtures.mjs           write the file
//   node tools/generate-demo-fixtures.mjs --check   exit 1 if the file is out of date
//
// Offline only: no network, no database.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src/lib/demo/fixtures.generated.ts");
const CODES = ["student", "worker", "at_risk"];

function fail(message) {
  console.error(`generate-demo-fixtures: ${message}`);
  process.exit(1);
}

const read = (rel) => readFileSync(join(root, rel), "utf8");
const personasFile = JSON.parse(read("mock-data/personas.json"));
const recurringFile = JSON.parse(read("mock-data/recurring-items.json"));
const goalsFile = JSON.parse(read("mock-data/savings-goals.json"));

const csvLines = read("mock-data/transactions.csv").trim().split(/\r?\n/);
const header = csvLines[0].split(",");
const EXPECTED_HEADER = ["persona_code", "occurred_at", "kind", "amount_vnd", "category", "merchant", "description"];
if (header.join(",") !== EXPECTED_HEADER.join(",")) fail(`unexpected CSV header: ${header.join(",")}`);

const amount = (value, what) => {
  const text = String(value);
  if (!/^(0|[1-9][0-9]{0,15})$/.test(text) || BigInt(text) > BigInt(Number.MAX_SAFE_INTEGER)) {
    fail(`invalid VND amount for ${what}: ${text}`);
  }
  return text;
};

const csvRows = csvLines.slice(1).map((line, index) => {
  if (line.includes('"')) fail(`CSV line ${index + 2} uses quotes; extend the parser before adding such rows`);
  const cells = line.split(",");
  if (cells.length !== EXPECTED_HEADER.length) fail(`CSV line ${index + 2} has ${cells.length} columns`);
  return Object.fromEntries(EXPECTED_HEADER.map((name, i) => [name, cells[i]]));
});

const personas = {};
for (const code of CODES) {
  const p = personasFile.personas.find((row) => row.code === code);
  if (!p) fail(`persona ${code} missing in personas.json`);
  const goal = goalsFile.find((row) => row.persona_code === code);
  if (!goal) fail(`goal for ${code} missing`);
  personas[code] = {
    code,
    displayName: p.display_name,
    story: p.story,
    profile: {
      balanceSnapshotVnd: amount(p.balance_snapshot_vnd, `${code}.balance_snapshot_vnd`),
      expectedMonthlyIncomeVnd: amount(p.expected_monthly_income_vnd, `${code}.expected_monthly_income_vnd`),
      paydayDay: p.payday_day,
      expectedDailyExpenseVnd: amount(p.expected_daily_expense_vnd, `${code}.expected_daily_expense_vnd`),
      projectedMonthlyBudgetVnd: amount(p.projected_monthly_budget_vnd, `${code}.projected_monthly_budget_vnd`),
      minimumReserveVnd: amount(p.minimum_reserve_vnd, `${code}.minimum_reserve_vnd`),
    },
    recurringItems: recurringFile
      .filter((row) => row.persona_code === code)
      .map((row) => ({
        label: row.label,
        kind: row.kind,
        amountVnd: amount(row.amount_vnd, `${code}.recurring.${row.label}`),
        dayOfMonth: row.day_of_month,
        category: row.category,
        startDate: row.start_date,
        active: row.active,
      })),
    transactions: csvRows
      .filter((row) => row.persona_code === code)
      .map((row) => ({
        occurredAt: row.occurred_at,
        kind: row.kind,
        amountVnd: amount(row.amount_vnd, `${code}.transaction`),
        category: row.category,
        merchant: row.merchant,
        description: row.description,
      })),
    goal: {
      name: goal.name,
      targetVnd: amount(goal.target_vnd, `${code}.goal.target`),
      savedVnd: amount(goal.saved_vnd, `${code}.goal.saved`),
      targetDate: goal.target_date,
    },
  };
}

const fixtures = {
  referenceDate: personasFile.reference_date,
  timezone: personasFile.timezone,
  personas,
};

const output =
  "// GENERATED by tools/generate-demo-fixtures.mjs from mock-data/*. DO NOT EDIT.\n" +
  "// Synthetic demonstration data only. Regenerate with: npm run gen:demo-fixtures\n" +
  'import type { DemoFixtures } from "./fixture-types";\n\n' +
  `export const DEMO_FIXTURES: DemoFixtures = ${JSON.stringify(fixtures, null, 2)};\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== output) {
    fail("src/lib/demo/fixtures.generated.ts is out of date. Run: npm run gen:demo-fixtures");
  }
  console.log("demo fixtures are up to date");
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT}`);
}
